def label(key: str, layout: Layout) -> str:
    return _LABELS[key][LAYOUTS.index(layout)]


def text(value: object, layout: Layout) -> str:
    """How `value` is printed in `layout`: dates and numbers follow the style's formats."""
    style = STYLES[layout]
    if isinstance(value, date):
        return value.strftime(style.date_format)
    if isinstance(value, Decimal):
        return f"{value:,}" if style.thousands else str(value)
    return str(value)


@cache
def _country_names() -> dict[str, str]:
    return {row["code"]: row["name"] for row in read_csv("countries.csv")}


def country_name(code: str) -> str:
    return _country_names().get(code, code)


def port_text(port: Port) -> str:
    return f"{port.name} ({port.code})"


def party_lines(party: Party) -> tuple[str, ...]:
    address = party.address
    # The city follows the street line, before the state and PIN line of Indian addresses.
    first, *rest = address.lines
    return (party.name, first, address.city, *rest, country_name(address.country))


@dataclass(frozen=True)
class Grid:
    columns: tuple[str, ...]  # label keys
    rows: tuple[tuple[object, ...], ...]
    widths: tuple[float, ...]  # relative column widths


@dataclass(frozen=True)
class Sheet:
    title: str  # label key
    fields: tuple[tuple[str, object], ...]  # (label key, value) printed near the top
    parties: tuple[tuple[str, tuple[str, ...]], ...] = ()  # (label key, lines)
    grids: tuple[Grid, ...] = ()
    totals: tuple[tuple[str, object], ...] = ()  # printed after the grids
    notes: tuple[str, ...] = ()
    signatory: str | None = None  # "For <name>" above a stamp and signature


def compose(parts: list[tuple[Sheet, Layout]], rng: random.Random) -> bytes:
    """One PDF with each (sheet, layout) starting on a new page: a single document, or several
    saved into one file."""
    story: list[Flowable] = []
    for sheet, layout in parts:
        if story:
            story.append(PageBreak())
        story += _Painter(layout).story(sheet, rng)
    buffer = io.BytesIO()
    document = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        leftMargin=15 * mm,
        rightMargin=15 * mm,
        topMargin=15 * mm,
        bottomMargin=18 * mm,
        title=label(parts[0][0].title, parts[0][1]),
        author="ShipGen",
        creator="ShipGen synthetic test data",
        # A fixed creation date keeps the same seed's output identical byte for byte.
        invariant=True,
    )
    document.build(story, onFirstPage=_footer, onLaterPages=_footer)
    return buffer.getvalue()


def _footer(canvas: Canvas, _: object) -> None:
    canvas.saveState()
    canvas.setFont("Helvetica", 6.5)
    canvas.setFillColor(colors.grey)
    canvas.drawString(15 * mm, 9 * mm, SPECIMEN_NOTE)
    canvas.drawRightString(A4[0] - 15 * mm, 9 * mm, f"Page {canvas.getPageNumber()}")
    canvas.restoreState()


class _Painter:
    def __init__(self, layout: Layout) -> None:
        self.layout = layout
        self.style = STYLES[layout]
        self.body = ParagraphStyle("body", fontName=self.style.font, fontSize=8.5, leading=10.5)
        self.strong = ParagraphStyle("strong", parent=self.body, fontName=self.style.bold)
        self.right = ParagraphStyle("right", parent=self.body, alignment=TA_RIGHT)
        self.title = ParagraphStyle(
            "title",
            parent=self.strong,
            fontSize=14,
            leading=18,
            alignment=TA_LEFT if layout == "word" else TA_CENTER,
            spaceAfter=4 * mm,
        )
        self.width = A4[0] - 30 * mm

    def para(self, value: object, style: ParagraphStyle | None = None) -> Paragraph:
        return Paragraph(escape(text(value, self.layout)), style or self.body)

    def story(self, sheet: Sheet, rng: random.Random) -> list[Flowable]:
        layout = self.layout
        story: list[Flowable] = [self.para(label(sheet.title, layout), self.title)]
        fields = [(label(key, layout), value) for key, value in sheet.fields]
        story.extend(self.header(sheet, fields))
        for grid in sheet.grids:
            story += [Spacer(0, 4 * mm), self.grid(grid)]
        if sheet.totals:
            totals = [(label(key, layout), value) for key, value in sheet.totals]
            story += [Spacer(0, 3 * mm), self.fields(totals, self.width * 0.6, right=True)]
        for note in sheet.notes:
            story += [Spacer(0, 2 * mm), self.para(note)]
        if sheet.signatory is not None:
            signature = [
                self.para(sheet.signatory, self.strong),
                Stamp(sheet.signatory, rng),
                self.para("Authorised Signatory"),
            ]
            story += [Spacer(0, 6 * mm), KeepTogether(signature)]
        return story

    def header(self, sheet: Sheet, fields: list[tuple[str, object]]) -> list[Flowable]:
        blocks = [
            [self.para(f"{label(key, self.layout)}:", self.strong), *map(self.para, lines)]
            for key, lines in sheet.parties
        ]
        if self.layout == "erp":
            # Parties stacked on the left, reference fields on the right.
            left = [cell for block in blocks for cell in block]
            # Less the outer cell padding, so the field table stays inside its box.
            right = self.fields(fields, self.width * 0.55 - 12)
            table = Table([[left, right]], colWidths=[self.width * 0.45, self.width * 0.55])
            return [self.boxed(table)]
        if self.layout == "tally":
            # Fields in two columns first, then the parties side by side.
            flowables: list[Flowable] = [self.fields(fields, self.width, columns=2)]
            if blocks:
                widths = [self.width / len(blocks)] * len(blocks)
                flowables += [Spacer(0, 3 * mm), self.boxed(Table([blocks], colWidths=widths))]
            return flowables
        # Word: parties as paragraphs, then one "Label: value" line per field.
        lines: list[Flowable] = [cell for block in blocks for cell in [*block, Spacer(0, 2 * mm)]]
        lines += [self.para(f"{name}: {text(value, self.layout)}") for name, value in fields]
        return lines

    def boxed(self, table: Table) -> Table:
        commands: list[Any] = [
            ("BOX", (0, 0), (-1, -1), 0.6, colors.black),
            ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ]
        if self.style.grid:
            commands.append(("INNERGRID", (0, 0), (-1, -1), 0.3, colors.black))
        table.setStyle(TableStyle(commands))
        return table

    def fields(
        self,
        fields: list[tuple[str, object]],
        width: float,
        columns: int = 1,
        right: bool = False,
    ) -> Table:
        cells: list[list[object]] = [
            [self.para(name, self.strong), self.para(value)] for name, value in fields
        ]
        if columns == 2:
            half = (len(cells) + 1) // 2
            left, rest = cells[:half], cells[half:]
            rest += [["", ""]] * (len(left) - len(rest))
            cells = [a + b for a, b in zip(left, rest, strict=True)]
        table = Table(
            cells or [["", ""]],
            colWidths=[width / columns * 0.42, width / columns * 0.58] * columns,
            hAlign="RIGHT" if right else "LEFT",
        )
        commands: list[Any] = [("VALIGN", (0, 0), (-1, -1), "TOP")]
        if self.style.grid:
            commands.append(("GRID", (0, 0), (-1, -1), 0.3, colors.black))
        else:
            commands.append(("LINEBELOW", (0, 0), (-1, -1), 0.2, colors.grey))
        table.setStyle(TableStyle(commands))
        return table

    def grid(self, grid: Grid) -> Table:
        header = [self.para(label(key, self.layout), self.strong) for key in grid.columns]
        rows = [
            [self.para(v, self.right if isinstance(v, Decimal | int) else None) for v in row]
            for row in grid.rows
        ]
        total = sum(grid.widths)
        table = Table(
            [header, *rows],
            colWidths=[self.width * w / total for w in grid.widths],
            repeatRows=1,
        )
        commands: list[Any] = [
            ("VALIGN", (0, 0), (-1, -1), "TOP"),
            ("LINEBELOW", (0, 0), (-1, 0), 0.6, colors.black),
        ]
        if self.style.grid:
            commands.append(("GRID", (0, 0), (-1, -1), 0.3, colors.black))
        else:
            commands.append(("LINEBELOW", (0, 1), (-1, -1), 0.2, colors.grey))
        if self.layout == "erp":
            commands.append(("BACKGROUND", (0, 0), (-1, 0), colors.lightgrey))
        table.setStyle(TableStyle(commands))
        return table


class Stamp(Flowable):
    """A company stamp with a signature across it, drawn as vector graphics."""

    def __init__(self, signatory: str, rng: random.Random) -> None:
        super().__init__()
        self.name = signatory.removeprefix("For ").upper()
        self.angle = rng.uniform(-12, 12)
        self.ink = colors.Color(0.15, 0.2, rng.uniform(0.5, 0.7), alpha=0.85)
        self.strokes = [
            (rng.uniform(0, 8) * mm, rng.uniform(2, 14) * mm) for _ in range(rng.randint(5, 8))
        ]
        self.width, self.height = 60 * mm, 22 * mm

    def wrap(self, available_width: float, available_height: float) -> tuple[float, float]:
        return self.width, self.height

    def draw(self) -> None:
        canvas = self.canv
        canvas.saveState()
        canvas.translate(25 * mm, self.height / 2)
        canvas.rotate(self.angle)
        canvas.setStrokeColor(self.ink)
        canvas.setFillColor(self.ink)
        canvas.setLineWidth(1.2)
        canvas.roundRect(-22 * mm, -8 * mm, 44 * mm, 16 * mm, 2 * mm)
        canvas.roundRect(-20.5 * mm, -6.5 * mm, 41 * mm, 13 * mm, 1.5 * mm)
        canvas.setFont("Helvetica-Bold", 6)
        canvas.drawCentredString(0, 1 * mm, self.name[:40])
        canvas.setFont("Helvetica", 5)
        canvas.drawCentredString(0, -3 * mm, "AUTHORISED SIGNATORY")
        canvas.restoreState()
        # The signature: a scribble across the stamp.
        canvas.setStrokeColor(colors.Color(0.05, 0.05, 0.35))
        canvas.setLineWidth(0.9)
        path = canvas.beginPath()
        x = 10 * mm
        path.moveTo(x, 6 * mm)
        for dx, y in self.strokes:
            x += 4 * mm + dx
            path.curveTo(x - 3 * mm, y + 4 * mm, x - 1 * mm, y - 4 * mm, x, y)
        canvas.drawPath(path)
