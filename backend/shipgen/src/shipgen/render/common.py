Layout = Literal["erp", "tally", "word"]
LAYOUTS: tuple[Layout, ...] = ("erp", "tally", "word")
# Printed on every page, so a generated file can never pass for a real document.
SPECIMEN_NOTE = "Specimen generated by ShipGen for software testing. Not a real document."


@dataclass(frozen=True)
class Style:
    font: str
    bold: str
    date_format: str
    thousands: bool  # 1,234.50 or 1234.50
    grid: bool  # tables with a full grid, or rules between rows only


STYLES: dict[Layout, Style] = {
    "erp": Style("Helvetica", "Helvetica-Bold", "%d-%m-%Y", thousands=True, grid=True),
    "tally": Style("Courier", "Courier-Bold", "%d-%b-%Y", thousands=False, grid=True),
    "word": Style("Times-Roman", "Times-Bold", "%d/%m/%Y", thousands=True, grid=False),
}

